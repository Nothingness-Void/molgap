def test_cache_partial_eviction_retries_and_preserves_legacy_and_unknown(tmp_path, monkeypatch):
    from molgap.local_storage import SOURCE_CACHE_NAMESPACE, source_cache_session
    monkeypatch.setenv("MOLGAP_SOURCE_CACHE_MAX_ENTRIES", "1")
    namespace = tmp_path / SOURCE_CACHE_NAMESPACE
    namespace.mkdir()
    names = ("source.tar.gz", "SOURCE_COMMIT.txt", "SOURCE_ARCHIVE_SHA256.txt", "SOURCE_FILES.json")
    old, recent, unknown = [namespace / (letter * 64) for letter in "abc"]
    legacy = tmp_path / ("d" * 64)
    for directory in (old, recent, unknown, legacy):
        directory.mkdir()
        for name in names:
            (directory / name).write_bytes(b"synthetic generated bytes")
    (unknown / "checkpoint.pt").write_bytes(b"preserve unknown bytes")
    os.utime(old, (1_700_000_000, 1_700_000_000))
    os.utime(recent, (1_700_000_060, 1_700_000_060))
    original = Path.unlink
    interrupted = []
    def unlink(path, *args, **kwargs):
        original(path, *args, **kwargs)
        if path.parent == old and not interrupted:
            interrupted.append(True)
            raise OSError("synthetic interruption after first deletion")
    with monkeypatch.context() as interruption:
        interruption.setattr(Path, "unlink", unlink)
        with source_cache_session(tmp_path) as cache:
            assert cache == namespace
    assert old.exists() and len(list(old.iterdir())) == 3
    with source_cache_session(tmp_path):
        pass
    assert not old.exists()
    assert {p.name for p in recent.iterdir()} == set(names)
    assert {p.name for p in legacy.iterdir()} == set(names)
    assert (unknown / "checkpoint.pt").read_bytes() == b"preserve unknown bytes"


def test_cache_recovers_only_known_partial_build_intermediates(tmp_path, monkeypatch):
    from molgap.local_storage import SOURCE_CACHE_NAMESPACE, source_cache_session
    namespace = tmp_path / SOURCE_CACHE_NAMESPACE
    namespace.mkdir()
    names = ("source.tar.gz", "SOURCE_COMMIT.txt", "SOURCE_ARCHIVE_SHA256.txt", "SOURCE_FILES.json")
    partial = namespace / (".partial-" + "a" * 64 + "-abcdefgh")
    unknown = namespace / (".partial-" + "b" * 64 + "-abcdefgh")
    linked = namespace / (".partial-" + "c" * 64 + "-abcdefgh")
    published = namespace / ("d" * 64)
    retired = namespace / (".incomplete-" + "e" * 64 + "-" + "f" * 32)
    for directory in (partial, unknown, linked, published, retired):
        directory.mkdir()
        for name in names:
            (directory / name).write_bytes(b"synthetic final bytes")
            (directory / f".{name}.tmp").write_bytes(b"interrupted bundle write")
    (unknown / ".unknown.tmp").write_bytes(b"unknown source")
    original = Path.lstat
    def reparse(path, *args, **kwargs):
        if path == linked / ".source.tar.gz.tmp":
            return SimpleNamespace(st_mode=stat.S_IFREG, st_file_attributes=0x400)
        return original(path, *args, **kwargs)
    monkeypatch.setattr(Path, "lstat", reparse)
    with source_cache_session(tmp_path):
        pass
    assert not partial.exists()
    assert len(list(unknown.iterdir())) == 9
    assert all(len(list(directory.iterdir())) == 8 for directory in (linked, published, retired))


def retired(paths, suffix="b" * 32):
    path = paths.artifact_root / "source-packages/runtime-cache" / (".incomplete-" + "a" * 64 + "-" + suffix)
    path.mkdir(parents=True)
    (path / "source.tar.gz").write_bytes(b"reproducible source cache")
    return path


def test_default_dry_run_and_explicit_disposable_removal(tmp_path):
    paths = profile(tmp_path)
    target = retired(paths)
    scratch = paths.scratch_root / "molgap-live"
    scratch.mkdir(parents=True)
    (scratch / "result.pt").write_bytes(b"possible unique state")
    first = clean_local_storage(paths, tmp_path / "code")
    assert first["status"] == "DRY_RUN" and not first["executed"]
    by_path = {row["path"]: row for row in first["candidates"]}
    assert by_path[str(target)]["disposition"] == "DISPOSABLE_RETIRED_CACHE"
    assert by_path[str(scratch)]["reason"] == "SCRATCH_LIVENESS_UNKNOWN"
    assert target.exists() and (scratch / "result.pt").exists()
    with pytest.raises(ValueError, match="explicit"):
        clean_local_storage(paths, tmp_path / "code", execute=True)
    result = clean_local_storage(paths, tmp_path / "code", candidates=[target], execute=True)
    assert result["status"] == "REMOVED" and result["executed"]
    assert not target.exists() and (scratch / "result.pt").exists()


