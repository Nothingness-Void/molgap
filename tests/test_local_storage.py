@pytest.mark.parametrize("replacement_change", ["missing", "changed", "unchanged"])
def test_failed_preparation_retry_rechecks_remaining_replacement_bytes(
        failed_preparation, monkeypatch, replacement_change):
    case = failed_preparation
    payload = b"synthetic recovery kernel\n"
    for tree in (case.old, case.run / "prepared"):
        (tree / "kernel").mkdir()
        (tree / "kernel/entry.py").write_bytes(payload)
        (tree / "source_dataset").mkdir()
        (tree / "source_dataset/retired.py").write_bytes(b"already retired\n")
    original = Path.unlink
    already_removed = case.old / "source_dataset/retired.py"

    def interrupted(path, *args, **kwargs):
        if path.is_relative_to(case.old):
            original(already_removed)
            raise OSError("synthetic interruption after partial deletion")
        return original(path, *args, **kwargs)

    with monkeypatch.context() as interruption:
        interruption.setattr(Path, "unlink", interrupted)
        assert case.retire()[0]["status"] == "REPORT_ONLY"
    receipt_path = case.old.with_name(case.old.name + ".json")
    assert json.loads(receipt_path.read_bytes())["local_payload_retirement"]["status"] == "PENDING"
    assert not already_removed.exists()
    # Already removed old files need no replacement coverage on recovery.
    (case.run / "prepared/source_dataset/retired.py").unlink()
    replacement = case.run / "prepared/kernel/entry.py"
    if replacement_change == "missing":
        replacement.unlink()
    elif replacement_change == "changed":
        replacement.write_bytes(b"different replacement kernel\n")
    result = case.retire()[0]
    if replacement_change == "unchanged":
        assert result["status"] == "REMOVED" and not case.old.exists()
        assert replacement.read_bytes() == payload
    else:
        assert result["status"] == "REPORT_ONLY"
        assert result["reason"] == "Failed preparation contains unmatched bytes"
        assert (case.old / "kernel/entry.py").read_bytes() == payload
        assert json.loads(receipt_path.read_bytes())["local_payload_retirement"]["status"] == "PENDING"
