def _hold_source_cache(root, connection):
    from molgap.local_storage import source_cache_session
    with source_cache_session(root) as cache:
        connection.send(cache is not None)
        connection.recv()


@pytest.fixture
def cache_holder(tmp_path, monkeypatch):
    """A real second process holds the lock until released or terminated."""
    monkeypatch.setenv("MOLGAP_SOURCE_CACHE_MAX_ENTRIES", "8")
    context = multiprocessing.get_context("spawn")
    parent, child = context.Pipe()
    root = tmp_path / "shared-cache"
    process = context.Process(target=_hold_source_cache, args=(root, child), daemon=True)
    process.start()
    child.close()
    try:
        assert parent.poll(20), "Cache holder failed to acquire its lock"
        assert parent.recv()
        yield root, process, parent
    finally:
        if process.is_alive():
            process.terminate()
        process.join(10)
        parent.close()
        assert not process.is_alive()


def test_cache_lock_excludes_processes_and_crash_releases_without_lock_removal(cache_holder):
    from molgap.local_storage import SOURCE_CACHE_NAMESPACE, source_cache_session
    root, process, connection = cache_holder
    lock = root / SOURCE_CACHE_NAMESPACE / ".lock"
    assert lock.stat().st_size == 0  # Contenders never write the locked byte.
    with source_cache_session(root) as cache:
        assert cache is None
    assert process.is_alive()
    process.terminate()  # No Python finally/atexit runs in the holder.
    process.join(10)
    assert not process.is_alive() and lock.exists()
    with source_cache_session(root) as cache:
        assert cache == lock.parent
    assert lock.stat().st_size == 0


